#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Ko,
    Vi,
    Other,
}

/// Which language a question is written in: Hangul → Korean; Vietnamese letters
/// (ă â đ ê ô ơ ư or tone marks) → Vietnamese; other Latin text → other.
pub fn detect(text: &str) -> Lang {
    let (mut ko, mut vi, mut latin) = (0usize, 0usize, 0usize);
    for c in text.chars() {
        if ('\u{AC00}'..='\u{D7A3}').contains(&c) {
            ko += 1;
        } else if "ăâđêôơưĂÂĐÊÔƠƯàáãạảèéẹẻẽìíĩịỉòóõọỏùúũụủỳýỵỷỹÀÁÃẠẢÈÉẸẺẼÌÍĨỊỈÒÓÕỌỎÙÚŨỤỦỲÝỴỶỸ".contains(c) || ('\u{1EA0}'..='\u{1EF9}').contains(&c) {
            vi += 1;
        } else if c.is_ascii_alphabetic() {
            latin += 1;
        }
    }
    if ko > 0 && ko >= vi {
        Lang::Ko
    } else if vi > 0 {
        Lang::Vi
    } else if latin > 0 {
        Lang::Other
    } else {
        Lang::Ko
    }
}

/// Whether messages about a question should be Vietnamese: by the question's language,
/// and by the screen language when the question doesn't tell.
pub fn answer_in_vi(question: &str) -> bool {
    match detect(question) {
        Lang::Vi => true,
        Lang::Ko => false,
        Lang::Other => vi(),
    }
}

#[macro_export]
macro_rules! ft {
    ($ko:literal, $vi:literal) => {
        if $crate::i18n::vi() { format!($vi) } else { format!($ko) }
    };
    ($ko:literal, $vi:literal, $($rest:tt)*) => {
        if $crate::i18n::vi() { format!($vi, $($rest)*) } else { format!($ko, $($rest)*) }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_question_language_and_translates() {
        let _screen = test_lock();
        assert_eq!(detect("전세 보증금은 얼마야?"), Lang::Ko);
        assert_eq!(detect("Tiền đặt cọc thuê nhà là bao nhiêu?"), Lang::Vi);
        assert_eq!(detect("How much is the deposit?"), Lang::Other);
        assert_eq!(detect("Hợp đồng 전세 có gì?"), Lang::Vi); // a Vietnamese sentence with a Korean word
        assert_eq!(tr_in(true, "질문하기"), "Hỏi đáp");
        assert_eq!(tr_in(false, "질문하기"), "질문하기");
        assert_eq!(tr_in(true, "번역이 없는 문장"), "번역이 없는 문장");
        let p = crate::rag::prepare(&crate::model::Settings::default(), &crate::demo::default_agent(), &[], "Hợp đồng thuê nhà kết thúc khi nào?");
        assert!(p.system.contains("tiếng Việt"));
        let p = crate::rag::prepare(&crate::model::Settings::default(), &crate::demo::default_agent(), &[], "계약은 언제 끝나?");
        assert!(p.system.contains("한국어로 답하세요"));
    }
}

